var greekNames = [6]string{"price", "delta", "gamma", "vega", "theta", "rho"}

func resultFields(r BSMResult) [6]Dec {
	return [6]Dec{r.Price, r.Delta, r.Gamma, r.Vega, r.Theta, r.Rho}
}

func goldenInput(t testing.TB, kind OptionKind, s, k, tt, r, q, vol string) BSMInput {
	return BSMInput{Kind: kind, Spot: d(t, s), Strike: d(t, k), TimeYears: d(t, tt), Rate: d(t, r), DividendYield: d(t, q), Vol: d(t, vol)}
}

func TestBlackScholesGolden(t *testing.T) {
	tol := d(t, "0.000000000000000000000000000000000001") // 1e-36
	worst := new(big.Float)
	o := oracle{prec: 400}
	for _, g := range bsmGolden {
		t.Run(g.name, func(t *testing.T) {
			for _, kind := range []OptionKind{Call, Put} {
				in := goldenInput(t, kind, g.s, g.k, g.t, g.r, g.q, g.vol)
				res, err := BlackScholes(in)
				require.NoError(t, err)
				require.Equal(t, RegimeAnalytic, res.Regime)
				want := g.call
				if kind == Put {
					want = g.put
				}
				got := resultFields(res)
				for i := range got {
					w, _ := o.f().SetString(want[i])
					if diff := absDiff(got[i], w); diff.Cmp(worst) > 0 {
						worst.Set(diff)
					}
					requireWithin(t, string(kind)+" "+greekNames[i], got[i], w, tol)
				}
				price, err := BlackScholesPrice(in)
				require.NoError(t, err)
				requireDecEqual(t, res.Price, price, "BlackScholesPrice must equal BlackScholes().Price")
				for key, printed := range g.textbook {
					kindName, field, _ := strings.Cut(key, ".")
					if (kindName == "call") != (kind == Call) {
						continue
					}
					v := got[slices.Index(greekNames[:], field)]
					require.True(t, v.Sub(d(t, printed)).Abs().Cmp(d(t, g.textbookTol)) <= 0,
						"%s %s: %s vs printed %s (± %s)", kind, key, v, printed, g.textbookTol)
				}
			}
		})
	}
	t.Logf("largest deviation from the 2000-bit goldens: %s", worst.Text('g', 4))
}

func TestBlackScholesHelpers(t *testing.T) {
	res, err := BlackScholes(goldenInput(t, Call, "100", "100", "1", "0.05", "0", "0.2"))
	require.NoError(t, err)
	vp, err := res.Vega.Quo(DecFromInt64(100), money.RoundHalfEven)
	require.NoError(t, err)
	requireDecEqual(t, vp, res.VegaPerVolPoint())
	td, err := res.Theta.Quo(DecFromInt64(365), money.RoundHalfEven)
	require.NoError(t, err)
	requireDecEqual(t, td, res.ThetaPerDay())
	require.Equal(t, "0.37524", mustFixed(t, res.VegaPerVolPoint(), 5))
	require.Equal(t, "-0.01757", mustFixed(t, res.ThetaPerDay(), 5))
}

func mustFixed(t testing.TB, v Dec, scale int32) string {
	t.Helper()
	s, err := v.StringFixed(scale, money.RoundHalfEven)
	require.NoError(t, err)
	return s
}

func TestBlackScholesValidation(t *testing.T) {
	base := func() BSMInput { return goldenInput(t, Call, "100", "100", "1", "0.05", "0", "0.2") }
	cases := []struct {
		field string
		mut   func(*BSMInput)
	}{
		{"kind", func(in *BSMInput) { in.Kind = "" }},
		{"kind", func(in *BSMInput) { in.Kind = "call" }},
		{"spot", func(in *BSMInput) { in.Spot = Dec{} }},
		{"spot", func(in *BSMInput) { in.Spot = d(t, "-1") }},
		{"spot", func(in *BSMInput) { in.Spot = d(t, "0.0000000000000000009") }},
		{"spot", func(in *BSMInput) { in.Spot = d(t, "1000000000000000000.1") }},
		{"strike", func(in *BSMInput) { in.Strike = Dec{} }},
		{"strike", func(in *BSMInput) { in.Strike = d(t, "1000000000000000001") }},
		{"time_years", func(in *BSMInput) { in.TimeYears = Dec{} }},
		{"time_years", func(in *BSMInput) { in.TimeYears = d(t, "-0.5") }},
		{"time_years", func(in *BSMInput) { in.TimeYears = d(t, "100.0000000000000000000000000000000000000001") }},
		{"vol", func(in *BSMInput) { in.Vol = Dec{} }},
		{"vol", func(in *BSMInput) { in.Vol = d(t, "-0.2") }},
		{"vol", func(in *BSMInput) { in.Vol = d(t, "10.0000000000000000000000000000000000000001") }},
		{"rate", func(in *BSMInput) { in.Rate = d(t, "1.0000000000000000000000000000000000000001") }},
		{"rate", func(in *BSMInput) { in.Rate = d(t, "-2") }},
		{"dividend_yield", func(in *BSMInput) { in.DividendYield = d(t, "-1.0000000000000000000000000000000000000001") }},
	}
	for _, tc := range cases {
		in := base()
		tc.mut(&in)
		_, err := BlackScholes(in)
		e := requireCode(t, err, errs.CodeValidationFailed)
		require.Equal(t, tc.field, e.Fields["field"], "%+v", in)
		_, err = BlackScholesPrice(in)
		requireCode(t, err, errs.CodeValidationFailed)
	}
	// The domain edges themselves are accepted.
	in := base()
	in.Spot, in.Strike = d(t, "0.000000000000000001"), d(t, "1000000000000000000")
	in.TimeYears, in.Vol = d(t, "100"), d(t, "10")
	in.Rate, in.DividendYield = d(t, "-1"), d(t, "1")
	_, err := BlackScholes(in)
	require.NoError(t, err)
	in.Rate, in.DividendYield = d(t, "1"), d(t, "-1")
	_, err = BlackScholes(in)
	require.NoError(t, err)
}
